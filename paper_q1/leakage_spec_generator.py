"""
Generate leakage_numbers.sty / .tex from leakage_ladder.json.

Every number in the leakage manuscript comes from this file. No number is
typed by hand, so a stale result cannot survive a rebuild.

Run:
    python -m paper_q1.leakage_spec_generator
"""
from __future__ import annotations

import json
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
RESULT = REPO_ROOT / "paper_q1" / "results" / "leakage_ladder.json"
OUT_DIR = REPO_ROOT / "paper_q1" / "manuscript_leakage"
OUT_TEX = OUT_DIR / "leakage_numbers.tex"
OUT_STY = OUT_DIR / "leakage_numbers.sty"

RUNG = {"P0": "Pzero", "P1": "Pone", "P2": "Ptwo", "P3": "Pthree"}
TRANSFORM = {"bands": "Bands", "raw": "Raw", "bands_env": "BandsEnv"}
METRIC = {
    "macro_f1": "MacroFone",
    "balanced_accuracy": "BalancedAccuracy",
    "auroc": "Auroc",
    "pr_auc": "Prauc",
    "brier": "Brier",
}
MODEL = {
    "MLP_16_32_16_2": "Mlp",
    "SVM_RBF": "SvmRbf",
    "LogisticRegression": "LogisticRegression",
    "RandomForest": "RandomForest",
    "HistGradientBoosting": "HistGradientBoosting",
}


def camel_model(name: str) -> str:
    return MODEL.get(name, name.replace("_", ""))


def camel_transform(name: str) -> str:
    return TRANSFORM.get(name, name.replace("_", "").title())


def fmt(x: float) -> str:
    return f"{x:.4f}"


def main() -> int:
    if not RESULT.exists():
        raise SystemExit(f"missing {RESULT}; run paper_q1.leakage_ladder first")
    data = json.loads(RESULT.read_text(encoding="utf-8"))
    meta = data["metadata"]
    experiments = data["experiments"]

    lines: list[str] = [
        "% AUTO-GENERATED by paper_q1/leakage_spec_generator.py",
        "% Source: paper_q1/results/leakage_ladder.json",
        "% Do not edit by hand. Rebuild instead.",
        "",
    ]

    for k, v in (
        ("NRows", meta["n_rows"]),
        ("NHives", meta["n_hives"]),
        ("NSeeds", len(meta["seeds"])),
        ("NBootstrap", meta["bootstrap_resamples"]),
    ):
        lines.append(f"\\newcommand{{\\Leak{k}}}{{{v}}}")

    lines.append("")
    for tname in experiments:
        n_feat = meta["transforms"][tname]
        lines.append(f"\\newcommand{{\\Leak{camel_transform(tname)}NFeatures}}{{{n_feat}}}")

    # dataset composition, read from the feature file so it cannot drift
    feat_csv = REPO_ROOT / "data" / "processed" / "mspb_colony_strength_features.csv"
    if feat_csv.exists():
        import pandas as pd  # local import keeps the module importable without it
        df = pd.read_csv(feat_csv)
        lines.append(f"\\newcommand{{\\LeakNStrong}}{{{int(df['is_strong'].sum())}}}")
        lines.append(f"\\newcommand{{\\LeakNWeak}}{{{int((1 - df['is_strong']).sum())}}}")
        lines.append(f"\\newcommand{{\\LeakNInspections}}{{{len(df)}}}")
        if "apiary" not in df.columns:
            cache = REPO_ROOT / "data" / "processed" / "tag_to_apiary.parquet"
            if cache.exists():
                m = pd.read_parquet(cache)[["tag_number", "apiary"]]
                df = df.merge(m, left_on="sensor_tag", right_on="tag_number", how="left")
        if "apiary" in df.columns and df["apiary"].notna().all():
            counts = df.groupby("apiary")["hive_id"].nunique().sort_index()
            vals = list(counts.values)
            if len(vals) == 2:
                lines.append(f"\\newcommand{{\\LeakNApiaryOne}}{{{vals[0]}}}")
                lines.append(f"\\newcommand{{\\LeakNApiaryTwo}}{{{vals[1]}}}")

    lines.append("")
    for tname, block in experiments.items():
        t = camel_transform(tname)
        for key, res in block.items():
            rung, model = key.split("|", 1)
            r, m = RUNG[rung], camel_model(model)
            metrics = res["metrics"]
            ci = res.get("ci95", {})
            for mkey, mname in METRIC.items():
                if mkey not in metrics:
                    continue
                val = metrics[mkey]
                if isinstance(val, float) and val != val:
                    continue
                lines.append(f"\\newcommand{{\\Leak{t}{r}{m}{mname}}}{{{fmt(val)}}}")
                if mkey in ci and len(ci[mkey]) == 2:
                    lo, hi = ci[mkey]
                    lines.append(f"\\newcommand{{\\Leak{t}{r}{m}{mname}CILo}}{{{fmt(lo)}}}")
                    lines.append(f"\\newcommand{{\\Leak{t}{r}{m}{mname}CIHi}}{{{fmt(hi)}}}")

    # gaps per transform, per model
    lines.append("")
    for tname, block in experiments.items():
        t = camel_transform(tname)
        models = sorted({k.split("|", 1)[1] for k in block})
        for model in models:
            m = camel_model(model)
            try:
                f1 = {r: block[f"{r}|{model}"]["metrics"]["macro_f1"] for r in RUNG}
            except KeyError:
                continue
            lines.append(f"\\newcommand{{\\Leak{t}HiveGap{m}}}{{{f1['P1'] - f1['P2']:+.4f}}}")
            lines.append(f"\\newcommand{{\\Leak{t}EnvGap{m}}}{{{f1['P2'] - f1['P3']:+.4f}}}")
            lines.append(f"\\newcommand{{\\Leak{t}TotalGap{m}}}{{{f1['P0'] - f1['P2']:+.4f}}}")
            # verbatim percentages for prose
            for r in RUNG:
                lines.append(f"\\newcommand{{\\Leak{t}{RUNG[r]}{m}MacroFonePct}}"
                             f"{{{f1[r] * 100:.1f}}}")

    # headline model: best P2 on the primary transform, chosen before P3
    primary = "bands" if "bands" in experiments else next(iter(experiments))
    block = experiments[primary]
    p2_models = [k.split("|", 1)[1] for k in block if k.startswith("P2|")]
    best = max(p2_models, key=lambda mo: block[f"P2|{mo}"]["metrics"]["macro_f1"])
    lines.append("")
    lines.append(f"\\newcommand{{\\LeakHeadlineModel}}{{{best}}}")
    lines.append(f"\\newcommand{{\\LeakHeadlineModelCamel}}{{{camel_model(best)}}}")

    # pre-registered verdict, per transform and model
    lines.append("")
    for tname, block in experiments.items():
        t = camel_transform(tname)
        models = sorted({k.split("|", 1)[1] for k in block})
        for model in models:
            m = camel_model(model)
            try:
                gap = (block[f"P0|{model}"]["metrics"]["macro_f1"]
                       - block[f"P2|{model}"]["metrics"]["macro_f1"])
                ci = block[f"P0|{model}"]["ci95"]["macro_f1"]
            except KeyError:
                continue
            se = (ci[1] - ci[0]) / 3.92
            verdict = "supported" if gap > 2 * se else ("weakened" if gap > se else "falsified")
            lines.append(f"\\newcommand{{\\Leak{t}Verdict{m}}}{{{verdict}}}")

    body = "\n".join(lines) + "\n"
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text(body, encoding="utf-8")
    OUT_STY.write_text(body, encoding="utf-8")

    print(f"wrote {OUT_TEX}")
    print(f"wrote {OUT_STY}")
    print(f"macros: {body.count(chr(92) + 'newcommand')}")
    print(f"primary transform: {primary}")
    print(f"headline model (best P2): {best}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
