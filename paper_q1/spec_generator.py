"""
paper_q1.spec_generator: Generates C headers, Python structs, and LaTeX macros
from the canonical specification in spec/beevil_spec.yaml.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Dict, Any
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent


def load_spec(spec_path: Path) -> Dict[str, Any]:
    with open(spec_path, "r", encoding="utf-8") as f:
        return yaml.safe_load(f)


def generate_c_header(spec: Dict[str, Any], output_path: Path) -> None:
    lines = [
        "/**",
        " * ============================================================================",
        " * BEEVIL KNIEVEL CANONICAL SPECIFICATION HEADER (AUTO-GENERATED)",
        " * ============================================================================",
        " * Generated by python -m paper_q1.run spec from spec/beevil_spec.yaml",
        " * DO NOT EDIT DIRECTLY.",
        " * ============================================================================",
        " */",
        "",
        "#ifndef BEEVIL_SPEC_GEN_H",
        "#define BEEVIL_SPEC_GEN_H",
        "",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "// --- SYSTEM ARCHITECTURE ---",
        f'#define BEEVIL_PROJECT_NAME            "{spec["system"]["project_name"]}"',
        f'#define BEEVIL_NODE_MCU                "{spec["system"]["node_mcu"]}"',
        "",
        "// --- BATTERY & POWER SUBSYSTEM ---",
        f'#define BEEVIL_BATTERY_CAPACITY_MAH    {spec["battery"]["capacity_mah"]}',
        f'#define BEEVIL_BATTERY_CAPACITY_MWH    {spec["battery"]["capacity_mwh"]}',
        f'#define BEEVIL_BATTERY_NOMINAL_VOLT    {spec["battery"]["nominal_voltage_v"]}f',
        f'#define BEEVIL_BATTERY_MAX_VOLT        {spec["battery"]["max_voltage_v"]}f',
        f'#define BEEVIL_BATTERY_CUTOFF_VOLT     {spec["battery"]["cutoff_voltage_v"]}f',
        "",
        "// --- RADIO CONFIGURATION (SX1262) ---",
        f'#define BEEVIL_LORA_FREQ_MHZ           {spec["radio"]["frequency_mhz"]}f',
        f'#define BEEVIL_LORA_BANDWIDTH_KHZ      {spec["radio"]["bandwidth_khz"]}',
        f'#define BEEVIL_LORA_SPREADING_FACTOR   {spec["radio"]["spreading_factor"]}',
        f'#define BEEVIL_LORA_TX_POWER_DBM       {spec["radio"]["tx_power_dbm"]}',
        f'#define BEEVIL_LORA_PREAMBLE_LEN       {spec["radio"]["preamble_symbols"]}',
        f'#define BEEVIL_LORA_AIRTIME_V1_MS      {spec["radio"]["airtime_v1_33b_ms"]}f',
        f'#define BEEVIL_LORA_AIRTIME_V2_MS      {spec["radio"]["airtime_v2_36b_ms"]}f',
        "",
        "// --- SENSOR PRESENCE BITMASKS ---",
    ]

    for k, v in spec["presence_flags"].items():
        lines.append(f"#define {k:<30} 0x{v:04X}")

    lines.extend([
        "",
        "// --- DISCRETE ALERT BITMASKS ---",
    ])
    for k, v in spec["alert_flags"].items():
        lines.append(f"#define {k:<30} 0x{v:02X}")

    lines.extend([
        "",
        "// --- DSP & AUDIO SUBSYSTEM ---",
        f'#define BEEVIL_DSP_CAPTURE_FS          {spec["dsp"]["capture_sample_rate_hz"]}',
        f'#define BEEVIL_DSP_DECIMATION_FACTOR   {spec["dsp"]["decimation_factor"]}',
        f'#define BEEVIL_DSP_PROCESSING_FS       {spec["dsp"]["processing_sample_rate_hz"]}',
        f'#define BEEVIL_DSP_FFT_POINTS          {spec["dsp"]["fft_length"]}',
        f'#define BEEVIL_DSP_BIN_RES_HZ          {spec["dsp"]["bin_resolution_hz"]}f',
        f'#define BEEVIL_DSP_NUM_BANDS           {len(spec["dsp"]["bands"])}',
        "",
        "// DSP Band Edges (Hz)",
    ])

    for b in spec["dsp"]["bands"]:
        idx = b["index"]
        lines.append(f'#define BEEVIL_DSP_BAND{idx}_MIN_HZ         {b["f_min_hz"]}')
        lines.append(f'#define BEEVIL_DSP_BAND{idx}_MAX_HZ         {b["f_max_hz"]}')

    lines.extend([
        "",
        "// --- CUSUM ALGORITHM PARAMETERS ---",
        f'#define BEEVIL_CUSUM_BASELINE_HOURS    {spec["cusum"]["rolling_baseline_window_hours"]}',
        f'#define BEEVIL_CUSUM_SLACK_K_C         {spec["cusum"]["slack_parameter_k_c"]}f',
        f'#define BEEVIL_CUSUM_THRESHOLD_H_C     {spec["cusum"]["decision_threshold_h_c"]}f',
        "",
        "// ----------------------------------------------------------------------------",
        "// WIRE PROTOCOL PAYLOAD DEFINITIONS",
        "// ----------------------------------------------------------------------------",
        "#pragma pack(push, 1)",
        "",
        "// Legacy 33-Byte Payload (v1)",
        "typedef struct {",
        "    uint16_t hive_id;                  // 2 bytes: Unique Hive ID",
        "    int16_t  brood_core_temp_c_x100;   // 2 bytes: TMP117 Temp (-9999 if sentinel)",
        "    int16_t  frame_temps_c_x100[5];    // 10 bytes: 5x DS18B20 Probes",
        "    uint16_t humidity_pct_x100;        // 2 bytes: 0-100% scaled x100",
        "    uint16_t voc_gas_kohm_x10;         // 2 bytes: kOhms scaled x10",
        "    uint16_t co2_ppm;                  // 2 bytes: SCD41 CO2 (400-10000)",
        "    uint16_t weight_kg_x100;           // 2 bytes: HX711 gross kg scaled x100",
        "    uint16_t lux;                      // 2 bytes: VEML7700 Lux",
        "    uint8_t  tilt_deg;                 // 1 byte: Tilt angle (OR'd with flags in v1)",
        "    uint8_t  fft_energy_bands[8];      // 8 bytes: Normalized acoustic sub-bands",
        "} BeevilPayloadV1;                     // sizeof == 33 bytes",
        "",
        "// Canonical 36-Byte Payload (v2 - Fixes alert collision & adds sequence counter)",
        "typedef struct {",
        "    uint16_t hive_id;                  // 2 bytes: Unique Hive ID (0x0001 - 0xFFFF)",
        "    uint16_t seq;                      // 2 bytes: Rolling Sequence Counter (0 - 65535)",
        "    int16_t  brood_core_temp_c_x100;   // 2 bytes: TMP117 Temp (-9999 if sentinel)",
        "    int16_t  frame_temps_c_x100[5];    // 10 bytes: 5x DS18B20 Probes (-9999 if sentinel)",
        "    uint16_t humidity_pct_x100;        // 2 bytes: Relative Humidity scaled x100",
        "    uint16_t voc_gas_kohm_x10;         // 2 bytes: VOC Gas Resistance scaled x10",
        "    uint16_t co2_ppm;                  // 2 bytes: Sensirion SCD41 CO2 ppm",
        "    uint16_t weight_kg_x100;           // 2 bytes: Hive scale gross kg scaled x100",
        "    uint16_t lux;                      // 2 bytes: Ambient Lux",
        "    uint8_t  tilt_deg;                 // 1 byte: STRICT physical tilt angle (0 to 90 deg)",
        "    uint8_t  flags;                    // 1 byte: Discrete alert and status bitmask",
        "    uint8_t  fft_energy_bands[8];      // 8 bytes: Normalized acoustic sub-bands",
        "} BeevilPayloadV2;                     // sizeof == 36 bytes",
        "",
        "#pragma pack(pop)",
        "",
        "#define BEEVIL_PAYLOAD_V1_SIZE         sizeof(BeevilPayloadV1)",
        "#define BEEVIL_PAYLOAD_V2_SIZE         sizeof(BeevilPayloadV2)",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif // BEEVIL_SPEC_GEN_H",
    ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  [OK] Generated C Header: {output_path.relative_to(REPO_ROOT)}")


def generate_python_spec(spec: Dict[str, Any], output_path: Path) -> None:
    lines = [
        '"""',
        'gateway.beevil_spec: Auto-generated Python specification & frame parser.',
        'Generated by python -m paper_q1.run spec from spec/beevil_spec.yaml',
        'DO NOT EDIT DIRECTLY.',
        '"""',
        "",
        "import struct",
        "from typing import Dict, Any, Optional, Tuple",
        "",
        f'PAYLOAD_V1_FORMAT = "{spec["payload_v1"]["struct_format"]}"',
        f'PAYLOAD_V1_SIZE = {spec["payload_v1"]["size_bytes"]}',
        "",
        f'PAYLOAD_V2_FORMAT = "{spec["payload_v2"]["struct_format"]}"',
        f'PAYLOAD_V2_SIZE = {spec["payload_v2"]["size_bytes"]}',
        "",
        "# Alert Bitmasks",
    ]

    for k, v in spec["alert_flags"].items():
        lines.append(f"{k} = 0x{v:02X}")

    lines.extend([
        "",
        "# Presence Bitmasks",
    ])
    for k, v in spec["presence_flags"].items():
        lines.append(f"{k} = 0x{v:04X}")

    lines.extend([
        "",
        "# Battery & Radio Constants",
        f'BATTERY_CAPACITY_MAH = {spec["battery"]["capacity_mah"]}',
        f'AIRTIME_V1_MS = {spec["radio"]["airtime_v1_33b_ms"]}',
        f'AIRTIME_V2_MS = {spec["radio"]["airtime_v2_36b_ms"]}',
        "",
        "def unpack_payload(raw_bytes: bytes) -> Optional[Dict[str, Any]]:",
        '    """Unpacks either v1 (33 bytes) or v2 (36 bytes) LoRa binary telemetry frames."""',
        "    if len(raw_bytes) == PAYLOAD_V2_SIZE:",
        "        return unpack_payload_v2(raw_bytes)",
        "    elif len(raw_bytes) == PAYLOAD_V1_SIZE:",
        "        return unpack_payload_v1(raw_bytes)",
        "    else:",
        "        return None",
        "",
        "def unpack_payload_v2(raw_bytes: bytes) -> Optional[Dict[str, Any]]:",
        '    """Unpack canonical 36-byte v2 payload with explicit sequence counter and flags."""',
        "    if len(raw_bytes) != PAYLOAD_V2_SIZE:",
        "        return None",
        "    unpacked = struct.unpack(PAYLOAD_V2_FORMAT, raw_bytes)",
        "    return {",
        '        "version": 2,',
        '        "hive_id": unpacked[0],',
        '        "seq": unpacked[1],',
        '        "brood_core_temp": unpacked[2] / 100.0 if unpacked[2] != -9999 else None,',
        '        "frame_temps": [unpacked[3 + i] / 100.0 if unpacked[3 + i] != -9999 else None for i in range(5)],',
        '        "humidity": unpacked[8] / 100.0 if unpacked[8] != 65535 else None,',
        '        "voc_gas": unpacked[9] / 10.0 if unpacked[9] != 65535 else None,',
        '        "co2_ppm": float(unpacked[10]) if unpacked[10] != 65535 else None,',
        '        "weight_kg": unpacked[11] / 100.0 if unpacked[11] != 65535 else None,',
        '        "lux": float(unpacked[12]) if unpacked[12] != 65535 else None,',
        '        "tilt_deg": float(unpacked[13]) if unpacked[13] != 255 else None,',
        '        "flags": unpacked[14],',
        '        "alert_queenless_cusum": bool(unpacked[14] & ALERT_FLAG_QUEENLESS_CUSUM),',
        '        "alert_pre_swarm": bool(unpacked[14] & ALERT_FLAG_PRE_SWARM_ACOUSTIC),',
        '        "alert_low_battery": bool(unpacked[14] & ALERT_FLAG_LOW_BATTERY_SOC),',
        '        "alert_tamper": bool(unpacked[14] & ALERT_FLAG_TILT_TAMPER),',
        '        "fft_bands": list(unpacked[15:23]),',
        "    }",
        "",
        "def unpack_payload_v1(raw_bytes: bytes) -> Optional[Dict[str, Any]]:",
        '    """Unpack legacy 33-byte v1 payload (supporting backwards compatibility)."""',
        "    if len(raw_bytes) != PAYLOAD_V1_SIZE:",
        "        return None",
        "    unpacked = struct.unpack(PAYLOAD_V1_FORMAT, raw_bytes)",
        "    raw_tilt = unpacked[12]",
        "    # Separate embedded flags from tilt angle in legacy frame",
        "    flags = 0",
        "    if raw_tilt & 0x80:",
        "        flags |= ALERT_FLAG_QUEENLESS_CUSUM",
        "    if raw_tilt & 0x40:",
        "        flags |= ALERT_FLAG_PRE_SWARM_ACOUSTIC",
        "    if raw_tilt & 0x20:",
        "        flags |= ALERT_FLAG_LOW_BATTERY_SOC",
        "    if raw_tilt & 0x10:",
        "        flags |= ALERT_FLAG_TILT_TAMPER",
        "    clean_tilt = float(raw_tilt & 0x0F) if raw_tilt != 255 else None",
        "    return {",
        '        "version": 1,',
        '        "hive_id": unpacked[0],',
        '        "seq": 0,',
        '        "brood_core_temp": unpacked[1] / 100.0 if unpacked[1] != -9999 else None,',
        '        "frame_temps": [unpacked[2 + i] / 100.0 if unpacked[2 + i] != -9999 else None for i in range(5)],',
        '        "humidity": unpacked[7] / 100.0 if unpacked[7] != 65535 else None,',
        '        "voc_gas": unpacked[8] / 10.0 if unpacked[8] != 65535 else None,',
        '        "co2_ppm": float(unpacked[9]) if unpacked[9] != 65535 else None,',
        '        "weight_kg": unpacked[10] / 100.0 if unpacked[10] != 65535 else None,',
        '        "lux": float(unpacked[11]) if unpacked[11] != 65535 else None,',
        '        "tilt_deg": clean_tilt,',
        '        "flags": flags,',
        '        "alert_queenless_cusum": bool(flags & ALERT_FLAG_QUEENLESS_CUSUM),',
        '        "alert_pre_swarm": bool(flags & ALERT_FLAG_PRE_SWARM_ACOUSTIC),',
        '        "alert_low_battery": bool(flags & ALERT_FLAG_LOW_BATTERY_SOC),',
        '        "alert_tamper": bool(flags & ALERT_FLAG_TILT_TAMPER),',
        '        "fft_bands": list(unpacked[13:21]),',
        "    }",
    ])

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  [OK] Generated Python Spec: {output_path.relative_to(REPO_ROOT)}")


def generate_tex_spec(spec: Dict[str, Any], output_path: Path) -> None:
    lines = [
        "% Auto-generated by python -m paper_q1.run spec from spec/beevil_spec.yaml",
        "% DO NOT EDIT DIRECTLY.",
        r"\ProvidesPackage{spec}",
        "",
        f'\\newcommand{{\\specBatteryCapacityMah}}{{{spec["battery"]["capacity_mah"]}}}',
        f'\\newcommand{{\\specBatteryCapacityMwh}}{{{spec["battery"]["capacity_mwh"]}}}',
        f'\\newcommand{{\\specPayloadSizeVone}}{{{spec["payload_v1"]["size_bytes"]}}}',
        f'\\newcommand{{\\specPayloadSizeVtwo}}{{{spec["payload_v2"]["size_bytes"]}}}',
        f'\\newcommand{{\\specAirtimeVoneMs}}{{{spec["radio"]["airtime_v1_33b_ms"]}}}',
        f'\\newcommand{{\\specAirtimeVtwoMs}}{{{spec["radio"]["airtime_v2_36b_ms"]}}}',
        f'\\newcommand{{\\specLoraFreqMhz}}{{{spec["radio"]["frequency_mhz"]}}}',
        f'\\newcommand{{\\specLoraBandwidthKhz}}{{{spec["radio"]["bandwidth_khz"]}}}',
        f'\\newcommand{{\\specLoraSf}}{{{spec["radio"]["spreading_factor"]}}}',
        f'\\newcommand{{\\specLoraTxPowerDbm}}{{{spec["radio"]["tx_power_dbm"]}}}',
        f'\\newcommand{{\\specDspCaptureFs}}{{{spec["dsp"]["capture_sample_rate_hz"]}}}',
        f'\\newcommand{{\\specDspProcessingFs}}{{{spec["dsp"]["processing_sample_rate_hz"]}}}',
        f'\\newcommand{{\\specDspFftPoints}}{{{spec["dsp"]["fft_length"]}}}',
        f'\\newcommand{{\\specDspBinResHz}}{{{spec["dsp"]["bin_resolution_hz"]}}}',
        f'\\newcommand{{\\specCusumSlackK}}{{{spec["cusum"]["slack_parameter_k_c"]}}}',
        f'\\newcommand{{\\specCusumThresholdH}}{{{spec["cusum"]["decision_threshold_h_c"]}}}',
    ]

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  [OK] Generated TeX Spec: {output_path.relative_to(REPO_ROOT)}")


def generate_all_specs(spec_yaml_path: Path) -> int:
    spec = load_spec(spec_yaml_path)
    generate_c_header(spec, REPO_ROOT / "firmware" / "config" / "beevil_spec_gen.h")
    generate_python_spec(spec, REPO_ROOT / "gateway" / "beevil_spec.py")
    generate_tex_spec(spec, REPO_ROOT / "paper_q1" / "manuscript" / "spec.tex")
    print("[paper_q1] All specification targets successfully generated.")
    return 0
