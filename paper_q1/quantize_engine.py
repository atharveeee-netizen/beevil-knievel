"""
paper_q1.quantize_engine: Edge TinyML post-training quantization and C-header export.
Performs symmetric INT8 quantization on the candidate F0-MLP edge model
across all 15 frozen outer folds of the real MSPB colony strength task.
Computes memory footprint and generates firmware/config/tinyml_weights.h.

Provenance Tag: ANALYTICAL_MODEL (Quantization error model) / BUILD_ARTIFACT (Header size)
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path
from typing import Dict, Any, Tuple, List
import numpy as np
import pandas as pd
from sklearn.neural_network import MLPClassifier
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import balanced_accuracy_score

REPO_ROOT = Path(__file__).resolve().parent.parent


def quantize_symmetric_int8(weights: np.ndarray) -> Tuple[np.ndarray, float]:
    """
    Symmetric INT8 quantization:
    Scale S = max(|W|) / 127.0
    W_int8 = clip(round(W / S), -128, 127)
    """
    max_val = float(np.max(np.abs(weights)))
    if max_val == 0.0:
        return np.zeros_like(weights, dtype=np.int8), 1.0
    scale = max_val / 127.0
    quantized = np.clip(np.round(weights / scale), -128, 127).astype(np.int8)
    return quantized, scale


def generate_c_header(
    mlp_weights: List[np.ndarray],
    mlp_biases: List[np.ndarray],
    mlp_scales: List[float],
    scaler_mean: np.ndarray,
    scaler_scale: np.ndarray,
    header_path: Path
) -> None:
    """Generates pure C header with static const weights and zero-heap inference routine."""
    num_inputs = len(scaler_mean)
    l1_nodes = mlp_weights[0].shape[1]
    l2_nodes = mlp_weights[1].shape[1]
    num_classes = mlp_weights[2].shape[1]

    w0_q, s_w0 = quantize_symmetric_int8(mlp_weights[0])
    w1_q, s_w1 = quantize_symmetric_int8(mlp_weights[1])
    w2_q, s_w2 = quantize_symmetric_int8(mlp_weights[2])

    lines = [
        "// Auto-generated by paper_q1.quantize_engine. DO NOT EDIT BY HAND.",
        "#ifndef BEEVIL_TINYML_WEIGHTS_H",
        "#define BEEVIL_TINYML_WEIGHTS_H",
        "",
        "#include <stdint.h>",
        "#include <stdbool.h>",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "// -----------------------------------------------------------------------------",
        "// MODEL ARCHITECTURE & HYPERPARAMETERS (TinyML F0-MLP)",
        "// -----------------------------------------------------------------------------",
        f"#define TINYML_NUM_INPUTS       {num_inputs}",
        f"#define TINYML_MLP_LAYER1_NODES {l1_nodes}",
        f"#define TINYML_MLP_LAYER2_NODES {l2_nodes}",
        f"#define TINYML_MLP_NUM_CLASSES  {num_classes}",
        "",
        "// Feature Standardizer Mean & Scale",
        "static const float TINYML_SCALER_MEAN[16] = {",
        "    " + ", ".join(f"{x:.4f}f" for x in scaler_mean),
        "};",
        "static const float TINYML_SCALER_SCALE[16] = {",
        "    " + ", ".join(f"{x:.4f}f" for x in scaler_scale),
        "};",
        "",
        f"// Layer 1 Weights ({w0_q.shape[0]}x{w0_q.shape[1]}), Scale = {s_w0:.6f}f",
        f"static const int8_t TINYML_W1[{w0_q.shape[0]}][{w0_q.shape[1]}] = {{"
    ]
    for row in w0_q:
        lines.append("    {" + ", ".join(f"{int(v)}" for v in row) + "},")
    lines.append("};")
    lines.append(f"static const float TINYML_B1[{len(mlp_biases[0])}] = {{")
    lines.append("    " + ", ".join(f"{float(b):.6f}f" for b in mlp_biases[0]))
    lines.append("};")
    lines.append("")

    lines.append(f"// Layer 2 Weights ({w1_q.shape[0]}x{w1_q.shape[1]}), Scale = {s_w1:.6f}f")
    lines.append(f"static const int8_t TINYML_W2[{w1_q.shape[0]}][{w1_q.shape[1]}] = {{")
    for row in w1_q:
        lines.append("    {" + ", ".join(f"{int(v)}" for v in row) + "},")
    lines.append("};")
    lines.append(f"static const float TINYML_B2[{len(mlp_biases[1])}] = {{")
    lines.append("    " + ", ".join(f"{float(b):.6f}f" for b in mlp_biases[1]))
    lines.append("};")
    lines.append("")

    lines.append(f"// Layer 3 Output Weights ({w2_q.shape[0]}x{w2_q.shape[1]}), Scale = {s_w2:.6f}f")
    lines.append(f"static const int8_t TINYML_W3[{w2_q.shape[0]}][{w2_q.shape[1]}] = {{")
    for row in w2_q:
        lines.append("    {" + ", ".join(f"{int(v)}" for v in row) + "},")
    lines.append("};")
    lines.append(f"static const float TINYML_B3[{len(mlp_biases[2])}] = {{")
    lines.append("    " + ", ".join(f"{float(b):.6f}f" for b in mlp_biases[2]))
    lines.append("};")
    lines.append("")

    lines.extend([
        "// Zero-heap, static SRAM inference routine",
        "static inline uint8_t beevil_tinyml_predict(const float* raw_inputs) {",
        "    // Feature Standardization",
        f"    float x_norm[{num_inputs}];",
        f"    for (int i = 0; i < {num_inputs}; i++) {{",
        "        x_norm[i] = (raw_inputs[i] - TINYML_SCALER_MEAN[i]) / TINYML_SCALER_SCALE[i];",
        "    }",
        "",
        "    // Layer 1 (16 -> 16)",
        f"    float h1[{l1_nodes}];",
        f"    for (int j = 0; j < {l1_nodes}; j++) {{",
        "        float acc = 0.0f;",
        f"        for (int i = 0; i < {num_inputs}; i++) {{",
        "            acc += x_norm[i] * (float)TINYML_W1[i][j];",
        "        }",
        f"        acc = acc * {s_w0:.6f}f + TINYML_B1[j];",
        "        h1[j] = (acc > 0.0f) ? acc : 0.0f; // ReLU",
        "    }",
        "",
        "    // Layer 2 (16 -> 8)",
        f"    float h2[{l2_nodes}];",
        f"    for (int j = 0; j < {l2_nodes}; j++) {{",
        "        float acc = 0.0f;",
        f"        for (int i = 0; i < {l1_nodes}; i++) {{",
        "            acc += h1[i] * (float)TINYML_W2[i][j];",
        "        }",
        f"        acc = acc * {s_w1:.6f}f + TINYML_B2[j];",
        "        h2[j] = (acc > 0.0f) ? acc : 0.0f; // ReLU",
        "    }",
        "",
        "    // Layer 3 Output (8 -> 2)",
        f"    float logits[{num_classes}];",
        f"    for (int j = 0; j < {num_classes}; j++) {{",
        "        float acc = 0.0f;",
        f"        for (int i = 0; i < {l2_nodes}; i++) {{",
        "            acc += h2[i] * (float)TINYML_W3[i][j];",
        "        }",
        f"        logits[j] = acc * {s_w2:.6f}f + TINYML_B3[j];",
        "    }",
        "",
        "    return (logits[1] > logits[0]) ? 1 : 0;",
        "}",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
        "#endif // BEEVIL_TINYML_WEIGHTS_H",
        ""
    ])

    header_path.parent.mkdir(parents=True, exist_ok=True)
    header_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  [OK] Exported C TinyML header to {header_path.relative_to(REPO_ROOT)}")


def export_quantized() -> int:
    """Executes Phase 6 post-training quantization and memory footprint audit."""
    print("=== [paper_q1] Step: quantize ===")

    features_csv = REPO_ROOT / "data" / "processed" / "mspb_colony_strength_features.csv"
    if not features_csv.exists():
        print(f"  [ERROR] {features_csv} not found.")
        return 1

    df_feat = pd.read_csv(features_csv)
    f0_cols = [c for c in df_feat.columns if c.startswith("f0_")]
    X_f0 = df_feat[f0_cols].values.astype(np.float32)
    y = df_feat["is_strong"].values.astype(int)

    splits_file = REPO_ROOT / "paper_q1" / "splits" / "t4_mspb_splits.json"
    splits_data = json.loads(splits_file.read_text(encoding="utf-8"))

    fp32_scores = []
    int8_scores = []

    print(f"Evaluating FP32 vs Symmetric INT8 across all 15 outer folds...")

    # We also keep the model trained on seed_0 fold_0 for header export
    best_weights = None
    best_biases = None
    best_scales = None
    best_scaler = None

    for seed_key in ["seed_0", "seed_1", "seed_2"]:
        for f in splits_data["splits_by_seed"][seed_key]:
            tr_idx = np.array(f["train_indices"])
            te_idx = np.array(f["test_indices"])

            scaler = StandardScaler()
            X_tr = scaler.fit_transform(X_f0[tr_idx])
            X_te = scaler.transform(X_f0[te_idx])

            mlp = MLPClassifier(hidden_layer_sizes=(16, 8), max_iter=250, random_state=42)
            mlp.fit(X_tr, y[tr_idx])

            # FP32 evaluation
            fp32_pred = mlp.predict(X_te)
            fp32_scores.append(float(balanced_accuracy_score(y[te_idx], fp32_pred)))

            # INT8 Quantization evaluation
            w0_q, s0 = quantize_symmetric_int8(mlp.coefs_[0])
            w1_q, s1 = quantize_symmetric_int8(mlp.coefs_[1])
            w2_q, s2 = quantize_symmetric_int8(mlp.coefs_[2])

            # Forward pass using quantized weights
            h1 = np.maximum(0, (X_te @ (w0_q.astype(np.float32) * s0)) + mlp.intercepts_[0])
            h2 = np.maximum(0, (h1 @ (w1_q.astype(np.float32) * s1)) + mlp.intercepts_[1])
            logits = (h2 @ (w2_q.astype(np.float32) * s2)) + mlp.intercepts_[2]
            if logits.shape[1] == 1:
                int8_pred = (logits.flatten() > 0.0).astype(int)
            else:
                int8_pred = np.argmax(logits, axis=1)
            int8_scores.append(float(balanced_accuracy_score(y[te_idx], int8_pred)))

            if best_weights is None:
                best_weights = [w.copy() for w in mlp.coefs_]
                best_biases = [b.copy() for b in mlp.intercepts_]
                best_scales = [s0, s1, s2]
                best_scaler = scaler

    mean_fp32 = float(np.mean(fp32_scores))
    mean_int8 = float(np.mean(int8_scores))
    acc_delta = abs(mean_fp32 - mean_int8)

    print(f"  15-Fold FP32 Mean Balanced Accuracy: {mean_fp32 * 100:.2f}%")
    print(f"  15-Fold INT8 Mean Balanced Accuracy: {mean_int8 * 100:.2f}% (Delta = {acc_delta * 100:.2f}%)")

    # Generate C Header
    header_path = REPO_ROOT / "firmware" / "config" / "tinyml_weights.h"
    generate_c_header(
        mlp_weights=best_weights,
        mlp_biases=best_biases,
        mlp_scales=best_scales,
        scaler_mean=best_scaler.mean_,
        scaler_scale=best_scaler.scale_,
        header_path=header_path
    )

    # Calculate exact memory footprint
    w_bytes = sum(w.size for w in best_weights)  # 1 byte per INT8 weight
    b_bytes = sum(b.size * 4 for b in best_biases)  # 4 bytes per float bias
    total_flash_bytes = w_bytes + b_bytes + len(best_scaler.mean_) * 4 * 2
    ram_scratch_bytes = (16 + 16 + 8 + 2) * 4  # activations float buffer (168 bytes)

    print(f"  Memory Footprint:")
    print(f"    Flash Usage (Weights, Biases, Scaler): {total_flash_bytes} Bytes ({total_flash_bytes / 1024:.2f} KB) (Budget: 128 KB)")
    print(f"    RAM Scratchpad:                        {ram_scratch_bytes} Bytes ({ram_scratch_bytes / 1024:.2f} KB) (Budget: 64 KB)")

    results = {
        "metadata": {
            "title": "Beevil Knievel TinyML Quantization & Memory Audit",
            "provenance": "ANALYTICAL_MODEL",
            "build_artifact_provenance": "BUILD_ARTIFACT",
            "architecture": "MLP (16 -> 16 -> 8 -> 2)",
            "quantization_scheme": "Symmetric INT8 (weights) / Float32 (biases and activations)",
            "evaluation_protocol": "Protocol P-A (15 Outer Folds on Unseen Hives)",
            "date": "2026-10-23"
        },
        "accuracy": {
            "fp32_balanced_accuracy": round(mean_fp32, 4),
            "int8_balanced_accuracy": round(mean_int8, 4),
            "parity_delta": round(acc_delta, 4)
        },
        "memory_footprint": {
            "weight_bytes": int(w_bytes),
            "bias_bytes": int(b_bytes),
            "total_flash_bytes": int(total_flash_bytes),
            "flash_budget_bytes": 128 * 1024,
            "flash_utilization_pct": round((total_flash_bytes / (128 * 1024)) * 100, 2),
            "ram_scratchpad_bytes": int(ram_scratch_bytes),
            "ram_budget_bytes": 64 * 1024,
            "ram_utilization_pct": round((ram_scratch_bytes / (64 * 1024)) * 100, 2)
        }
    }

    out_json = REPO_ROOT / "paper_q1" / "results" / "edge_quantization.json"
    out_json.write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"[OK] Quantization complete. Results saved to {out_json.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(export_quantized())
