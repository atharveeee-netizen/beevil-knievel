"""
paper_q1.quantize_engine: Edge TinyML post-training quantization and C-header export.
Performs symmetric INT8 quantization on trained edge models (F0-MLP, F0-LogReg, DS-CNN),
measures memory footprints, verifies quantization parity (FP32 vs INT8),
and generates firmware/config/tinyml_weights.h for Cortex-M4F (RAK4631).
Provenance Tag: REAL_BENCH_MEASUREMENT (Model artifacts & memory sizes)
"""

