};

col_w = 0.142;
col_h = 0.70;
y_pos = 0.16;

for i = 1:6
    cx = 0.030 + (i-1) * 0.158;
    title_str = stages{i, 1};
    lines = stages{i, 2};
    tag = stages{i, 3};
    drawBlock(ax, [cx, y_pos, col_w, col_h], title_str, lines, style);
    drawEvidenceTag(ax, [cx + col_w - 0.082, y_pos + col_h - 0.025, 0.08, 0.022], tag, style);
    if i < 6
        drawArrow(ax, [cx + col_w, y_pos + col_h/2], [cx + 0.158, y_pos + col_h/2], '', style);
    end
end

labels = {'PHYSICAL', 'EDGE', 'EDGE / DSP', 'WIRELESS', 'GATEWAY / AI', 'DECISION'};
for i = 1:6
    cx = 0.030 + (i-1) * 0.158 + col_w/2;
    text(ax, cx, 0.100, labels{i}, 'FontName', style.font_family, 'FontSize', style.fs_subhead, ...
        'FontWeight', 'bold', 'Color', style.stroke_dark, 'HorizontalAlignment', 'center');
end

drawLegend(ax, [0.18, 0.016, 0.64, 0.036], style);

end
