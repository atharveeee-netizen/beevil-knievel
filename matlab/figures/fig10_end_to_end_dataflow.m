% Chronological 6-Stage Signal Transformation: Physical Phenomena to Beekeeper Decision [Video Frame Ready]

addpath(fullfile(fileparts(mfilename('fullpath')), '..', 'lib'));
style = createFigureStyle('standard');

fig = figure('Name', 'FIG 10: End-to-End Data Flow Pipeline', ...
    'Color', style.bg_color, ...
    'Position', [100, 100, style.width, style.height], ...
    'MenuBar', 'none', 'ToolBar', 'none');
ax = axes('Parent', fig, 'Position', [0, 0, 1, 1]);
hold(ax, 'on'); axis(ax, [0 1 0 1]); axis(ax, 'off');

% Header
text(ax, 0.035, 0.965, 'FIGURE 10: END-TO-END DATA FLOW PIPELINE', ...
    'FontName', style.font_family, 'FontSize', style.fs_title, 'FontWeight', 'bold', ...
    'Color', style.stroke_dark, 'VerticalAlignment', 'top');
text(ax, 0.035, 0.935, 'Chronological 6-Stage Signal Transformation: Physical Phenomena to Beekeeper Decision [Video Frame Ready]', ...
    'FontName', style.font_family, 'FontSize', style.fs_body, 'Color', style.stroke_med, 'VerticalAlignment', 'top');

stages = {
    'STAGE 1: PHYSICAL', ...
    {'Brood Core Thermal:', '34.5°C to 35.5°C', ...
     'Acoustic Vibrations:', '100–500 Hz Audio', ...
     'CO2 Respiration:', '400–5000 ppm', ...
     'Colony Mass Accum:', '0–100 kg Net Weight'}, 'VALIDATED';
    
    'STAGE 2: TRANSDUCTION', ...
